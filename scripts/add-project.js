#!/usr/bin/env node
/**
 * Create a project file in ./projects from command-line flags.
 *
 *   # autonomous (recommended): a mandate, the desk does the rest
 *   npm run project:add -- --id mytoken --name "My Token" --mint <MINT> --decimals 6 \
 *     --wallet <PUBKEY> --mode paper --cap 0.5 --budget 20 --budget-day 5 --delay 24 \
 *     --mandate balanced --horizon-days 30 --distribute-pct 50 --alert-floor 0.00012
 *
 *   # manual (legacy): the founder sets levels and pace himself
 *   npm run project:add -- ... --level 0.0002:10 --level 0.00015:10 --dist 0.3:strength --min-price 0.0001
 *
 * Everything not given takes the defaults from @tenfold/core.
 */
import { randomBytes } from "node:crypto";
import { saveProject, DEFAULT_RULES, DEFAULT_STRATEGY, strategyFromMandate, describeMandate } from "@tenfold/core";

const args = process.argv.slice(2);
const get = (k, d) => {
  const i = args.indexOf(`--${k}`);
  return i >= 0 ? args[i + 1] : d;
};
const all = (k) => args.flatMap((a, i) => (a === `--${k}` ? [args[i + 1]] : []));
const has = (k) => args.includes(`--${k}`);

if (has("help") || !get("id") || !get("mint") || !get("wallet")) {
  console.log(`usage: --id <slug> --name <name> --mint <mint> --decimals <n> --wallet <pubkey> [--mode paper|live]
  [--cap <pct/day>] [--budget <SOL>] [--budget-day <SOL>] [--delay 24|48] [--slippage <bps>]
  [--level <price>:<SOL>]... [--dist <pct>:<strength|twap>] [--min-price <price>]
  [--rebalance <targetSolShare>:<band>] [--clip <minSol>:<maxSol>] [--referral <code>]
  [--strength-boost <1..10>]  (sell harder into strong real up-moves, bounded by the cap)
  [--mandate protect|balanced|distribute] [--horizon-days <n>] [--distribute-pct <pct>] [--alert-floor <price>] [--autonomy auto|ask]
      (a mandate makes the desk place/move levels and set the pace itself; --level and --dist are then optional, levels given are pinned)
  [--bind-code <code> | --no-bind-code]  (Telegram bind secret; a random one is generated by default)`);
  process.exit(get("id") ? 0 : 1);
}

const levels = all("level").map((s) => {
  const [price, budgetSol] = s.split(":").map(Number);
  return { price, budgetSol };
});
const [distPct, distMode] = (get("dist", "") || "").split(":");
const [rebTarget, rebBand] = (get("rebalance", "") || "").split(":");
const [clipMin, clipMax] = (get("clip", "") || "").split(":");

const cfg = {
  id: get("id"),
  name: get("name", get("id")),
  mint: get("mint"),
  decimals: Number(get("decimals", "6")),
  walletPubkey: get("wallet"),
  mode: get("mode", "paper"),
  rules: {
    ...DEFAULT_RULES,
    dailySellCapPct: Number(get("cap", DEFAULT_RULES.dailySellCapPct)),
    defenseBudgetSol: Number(get("budget", DEFAULT_RULES.defenseBudgetSol)),
    maxDefenseSpendPerDaySol: Number(get("budget-day", get("budget", DEFAULT_RULES.maxDefenseSpendPerDaySol))),
    withdrawalDelayHours: Number(get("delay", DEFAULT_RULES.withdrawalDelayHours)),
    maxSlippageBps: Number(get("slippage", DEFAULT_RULES.maxSlippageBps)),
  },
  strategy: {
    defense: { enabled: levels.length > 0, levels },
    distribution: {
      enabled: Boolean(distPct),
      pctOfVaultPerDay: distPct ? Number(distPct) : DEFAULT_STRATEGY.distribution.pctOfVaultPerDay,
      mode: distMode === "twap" ? "twap" : "strength",
      ...(get("min-price") ? { minPrice: Number(get("min-price")) } : {}),
    },
    rebalance: {
      enabled: Boolean(rebTarget),
      targetSolShare: rebTarget ? Number(rebTarget) : DEFAULT_STRATEGY.rebalance.targetSolShare,
      band: rebBand ? Number(rebBand) : DEFAULT_STRATEGY.rebalance.band,
    },
    clip: {
      minSol: clipMin ? Number(clipMin) : DEFAULT_STRATEGY.clip.minSol,
      maxSol: clipMax ? Number(clipMax) : DEFAULT_STRATEGY.clip.maxSol,
      jitterPct: DEFAULT_STRATEGY.clip.jitterPct,
    },
  },
  ...(get("referral") ? { referral: get("referral") } : {}),
  createdAt: Date.now(),
  paused: false,
};

// A bind code closes the window where any chat that guesses the id could claim the project on Telegram.
// Generated by default; pass --bind-code <code> to set your own, or --no-bind-code to opt out (not for real funds).
if (get("bind-code")) cfg.bindCode = get("bind-code");
else if (!has("no-bind-code")) cfg.bindCode = randomBytes(5).toString("base64url");

if (get("strength-boost")) cfg.strategy.distribution.strengthBoost = Number(get("strength-boost"));

if (get("mandate")) {
  const profile = get("mandate");
  if (!["protect", "balanced", "distribute"].includes(profile)) {
    console.error("--mandate must be protect, balanced or distribute");
    process.exit(1);
  }
  const autonomy = get("autonomy", "auto");
  if (!["auto", "ask"].includes(autonomy)) {
    console.error("--autonomy must be auto or ask");
    process.exit(1);
  }
  const alertFloor = get("alert-floor") ? Number(get("alert-floor")) : 0;
  cfg.mandate = {
    profile,
    autonomy,
    ...(get("horizon-days") ? { horizonDays: Number(get("horizon-days")) } : {}),
    ...(get("distribute-pct") ? { distributePct: Number(get("distribute-pct")) } : {}),
    ...(alertFloor > 0 ? { alertFloor } : {}),
    startedAt: Date.now(),
  };
  const pinned = levels.map((l) => ({ ...l, pinned: true }));
  const minPrice = cfg.strategy.distribution.minPrice;
  cfg.strategy = strategyFromMandate(cfg.mandate, cfg);
  cfg.strategy.defense.levels = pinned;
  if (pinned.length > 0) cfg.strategy.defense.enabled = true;
  if (minPrice) cfg.strategy.distribution.minPrice = minPrice;
  const ignored = ["dist", "rebalance", "strength-boost"].filter((k) => has(k));
  if (ignored.length) console.log(`note: with --mandate the desk sets ${ignored.map((k) => "--" + k).join(", ")} itself; those flags were ignored`);
  if (pinned.length) console.log(`note: ${pinned.length} level(s) given with --level are pinned; the desk never moves them`);
}

saveProject(cfg);
if (cfg.mandate) console.log(`mandate: ${describeMandate(cfg.mandate)}`);
console.log(`project ${cfg.id} written to ${process.env.TENFOLD_PROJECTS_DIR ?? "./projects"}/${cfg.id}.json (mode ${cfg.mode})`);
if (cfg.bindCode) console.log(`bind code: ${cfg.bindCode}   (the founder binds with:  /start ${cfg.id} ${cfg.bindCode} )`);
